def find_gap(question: str) -> Gap | None:
    """คืนช่องว่างข้อมูลที่ตรงกับคำถาม ถ้าไม่มีคืน None"""
    q = (question or "").strip()
    for gap in COVERAGE_GAPS:
        if any(k in q for k in gap.keywords):
            return gap
    return None


